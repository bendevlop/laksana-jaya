create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null check (char_length(customer_name) between 1 and 80),
  customer_phone text not null check (char_length(customer_phone) between 5 and 20),
  service text not null check (char_length(service) between 1 and 100),
  details text not null check (char_length(details) between 1 and 1500),
  deadline text not null default 'Fleksibel',
  budget text not null default '',
  file_name text not null default '',
  status text not null default 'Menunggu'
    check (status in ('Menunggu','Diproses','Selesai','Dibatalkan')),
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  is_admin boolean not null default false
);

alter table public.orders enable row level security;
alter table public.profiles enable row level security;

-- Publik boleh membuat pesanan, tetapi tidak boleh membaca semua pesanan.
drop policy if exists "public can create orders" on public.orders;
create policy "public can create orders"
on public.orders for insert to anon, authenticated
with check (
  char_length(customer_name) between 1 and 80
  and char_length(customer_phone) between 5 and 20
  and char_length(service) between 1 and 100
  and char_length(details) between 1 and 1500
  and status = 'Menunggu'
);

-- Admin hanya bisa membaca/memperbarui pesanan jika profiles.is_admin = true.
drop policy if exists "admins can read orders" on public.orders;
create policy "admins can read orders"
on public.orders for select to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin = true));

drop policy if exists "admins can update orders" on public.orders;
create policy "admins can update orders"
on public.orders for update to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin = true))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin = true));

-- Pengguna hanya dapat membaca baris profilnya sendiri; jangan izinkan publik mengubah is_admin.
drop policy if exists "users can read own profile" on public.profiles;
create policy "users can read own profile"
on public.profiles for select to authenticated
using (id = auth.uid());

